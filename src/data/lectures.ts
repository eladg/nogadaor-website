// "72:36" → 73 (דקות צפייה, מעוגל)
export const minutesOf = (d: string) => {
  const parts = d.split(':').map(Number);
  const secs = parts.length === 3 ? parts[0] * 3600 + parts[1] * 60 + parts[2] : parts[0] * 60 + parts[1];
  return Math.round(secs / 60);
};
