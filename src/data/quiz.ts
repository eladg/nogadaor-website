export interface QuizQuestion {
  area: string;
  text: string;
  multi?: boolean; // לא בשימוש מגרסה 6 (נוגה: בלי שאלות עם כמה תשובות). הקוד עדיין תומך
  options: string[]; // 5 תשובות מהחזקה לחלשה
  topic: string; // שם קצר לנושא, מוצג רק בתוצאה
  why: string; // מה המשמעות של תשובה חלשה, ולמה זה שווה כסף
  tip: string; // העצה הראשונה, משהו שאפשר לעשות כבר השבוע
  together: string; // מה אפשר לעשות עם נוגה
  service: ServiceKey;
  res?: ResKey[]; // מדריכים, הדרכות והרצאות מתאימים. מדריך "בקרוב" מוסתר לבד, וחוזר כשהוא נפתח
  impact: 1 | 2 | 3; // כמה קרוב הנושא לכסף. קובע את הסדר בין עצות עם אותה תשובה
  // נוסח חלופי לעסק עם עובדים (לפי שאלת הפתיחה). רק מה שמשתנה. הניקוד והסדר של התשובות זהים
  team?: Partial<Pick<QuizQuestion, 'text' | 'options' | 'topic' | 'why' | 'tip' | 'together' | 'service' | 'res'>>;
  // עצה אחרת לתשובה מסוימת (המפתח: מקום התשובה ברשימה, מ-0), כשהתשובה הזו מלמדת משהו אחר משאר התשובות החלשות
  byAnswer?: Record<number, Partial<Pick<QuizQuestion, 'topic' | 'why' | 'tip' | 'together' | 'service' | 'res'>>>;
}

