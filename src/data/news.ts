export type NewsItem = {
  id: string; // עוגן בעמוד
  topic: string; // נושא קצר, מופיע מתחת לכותרת
  title: string;
  text: string;
  forBusiness: string; // "מה זה אומר לעסק שלך"
  sources: { label: string; url: string }[];
};

export type Update = {
  id: string;
  title: string;
  text: string;
  image?: string; // שם קובץ מתוך src/assets (ראו הטבלה בעמוד הגיליון)
  imagePending?: string; // תמונה שנוגה עוד צריכה לשלוח: מה אמור להיות בה
  link?: { href: string; label: string; external?: boolean };
  draft?: string; // הערה פנימית: מה עוד חסר (מוצג בעמוד כתיבה מקווקווה עד שמתמלא)
};

export type NewsEvent = {
  id: string;
  date: string; // YYYY-MM-DD
  time?: string;
  title: string;
  where: string;
  text: string;
  link?: { href: string; label: string };
  draft?: string;
};

