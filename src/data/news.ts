// אותם חפצים כמו ב-ContentCover.astro
export type CoverMotif = 'ai' | 'growth' | 'screen' | 'target' | 'gift' | 'iceberg' | 'chat' | 'megaphone' | 'compass';

export type Link = { href: string; label: string; external?: boolean };

export type Feature = {
  id: string;
  title: string;
  meta: string; // שורה קצרה מתחת לכותרת (סוג, תאריך)
  time?: string; // שעות, מוצג משמאל לימין
  text: string;
  image?: string; // שם קובץ מתוך src/assets
  imageAlt?: string;
  toon?: boolean; // איור של נוגה (חיתוך מלמעלה)
  cta: Link;
  tone: 'dark' | 'light';
};

export type Session = { date: string; day: string; areas: string; time: string; place: string };

export type Meetup = {
  id: string;
  title: string;
  text: string[];
  image: string;
  imageAlt: string;
  host: string; // שורה מתחת לתמונה
  question?: string; // משפט שמוביל לרשימת המפגשים
  sessions: Session[];
  cta: Link;
  note?: string;
};

export type NewsItem = {
  id: string;
  cover: { title: string; motif: CoverMotif; tone?: 'cool' | 'warm' }; // *מילה* בזהב, | ירידת שורה
  topic: string;
  badge?: string; // תאריך בולט על הכריכה, למשל 27.11
  title: string;
  text: string;
  forBusiness: string;
  sources: { label: string; url: string }[];
};

export type Update = {
  id: string;
  title: string;
  text: string;
  image?: string;
  imageAlt?: string;
  toon?: boolean;
  link?: Link;
  draft?: string; // מה עוד חסר (מוצג במסגרת מקווקווה)
};

