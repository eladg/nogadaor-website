export type CoverMotif = 'ai' | 'growth' | 'screen' | 'target' | 'gift' | 'iceberg' | 'chat' | 'megaphone' | 'compass';

export type Link = { href: string; label: string; external?: boolean };

export type Session = { date: string; day: string; time: string; areas: string };

// כרטיס ב"אצל נוגה". כולם באותו מבנה: תמונה 16:9, כותרת, שורת פרטים, טקסט קצר, "להמשך קריאה" (לא חובה), כפתור
export type NogaCard = {
  id: string;
  title: string;
  meta?: string;
  time?: string; // מוצג משמאל לימין
  text: string;
  more?: string[]; // פסקאות שנפתחות ב"להמשך קריאה"
  sessions?: Session[]; // גם הן בתוך "להמשך קריאה"
  image: string; // שם קובץ מתוך src/assets
  imageAlt?: string;
  contain?: boolean; // תמונת הזמנה עם טקסט: להציג את כולה, על רקע כהה
  cta?: Link;
};

export type NewsItem = {
  id: string;
  motif: CoverMotif; // התמונה של הכרטיס (בלי טקסט עליה)
  tone?: 'cool' | 'warm';
  badge?: string; // תאריך בולט על התמונה
  title: string;
  teaser: string; // משפט אחד שמופיע תמיד
  text: string; // ההמשך, נפתח ב"להמשך קריאה"
  sources: { label: string; url: string }[];
};

